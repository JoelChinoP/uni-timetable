BEGIN;

CREATE SCHEMA app;

CREATE TYPE app.mode_type AS ENUM ('THEORY', 'LABORATORY');
CREATE TYPE app.week_day AS ENUM (
  'MONDAY',
  'TUESDAY',
  'WEDNESDAY',
  'THURSDAY',
  'FRIDAY',
  'SATURDAY'
);

CREATE TABLE app.careers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(10) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE app.academic_hours (
  hour_number SMALLINT PRIMARY KEY CHECK (hour_number BETWEEN 1 AND 15),
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  CHECK (end_time > start_time)
);

